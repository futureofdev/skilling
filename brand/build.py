#!/usr/bin/env python3
"""Regenerate the Skilling brand pack.

The vector sources in ``assets/`` are the source of truth and are committed. Everything
this script writes is derived from them: rasters, the favicon set, the badge SVGs, the
contrast report, and the distributable zip.

Two stages, because they have different dependencies:

    uv run --with pillow brand/build.py
        Geometry rasters (tiles, favicons, .ico, mark PNGs, avatar) and the contrast
        report. Needs Pillow only. The contrast report needs nothing but stdlib.

    uv run --with pillow --with playwright brand/build.py --with-browser
        Also renders the text-bearing assets: README banners, social preview,
        email masthead, and the badge SVGs. These need a real browser because they need
        real Archivo, and because badge padding is measured rather than estimated.
        First run also needs: uv run --with playwright playwright install chromium

    uv run --with pillow brand/build.py --zip
        Assemble dist/skilling-brand-assets-v2.0.zip from whatever is present.

Pillow and Playwright are build-time tooling. They belong in a dependency group, never in
packages/skilling runtime deps.
"""

from __future__ import annotations

import argparse
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).parent
ASSETS = ROOT / "assets"
OUT = ROOT / "dist"
PACK = "skilling-brand-assets-v2.0"

# --- The Cut. The one geometric constant in the system. ---------------------------------
# 28x28 square at 0,4 on a 32x32 canvas, with two 4-deep, 20-long channels driven in from
# opposite sides. Bars are 8 / 4 / 4 / 4 / 8 = 28. Narrowest run is 4 units, which is 2px
# at the 16px floor.
MARK_PATH = "M0 4 H28 V12 H8 V16 H28 V32 H0 V24 H20 V20 H0 Z"
MARK_POLY = [(0, 4), (28, 4), (28, 12), (8, 12), (8, 16), (28, 16),
             (28, 32), (0, 32), (0, 24), (20, 24), (20, 20), (0, 20)]

INK = (17, 24, 39)
BUILD = (200, 255, 61)
CLOUD = (243, 245, 248)
WHITE = (255, 255, 255)

# Fields the mark may sit on. All lighter than Ink — this list is the field rule in code.
# A white mark is absent deliberately: reversed, the Cut reads as a mirrored S, tile or not.
FIELDS = {"cloud": CLOUD, "build": BUILD, "white": WHITE}


# ---------------------------------------------------------------------------------------
# Contrast — stdlib only, so the report is always regenerable
# ---------------------------------------------------------------------------------------

PALETTE = {
    "Ink": "#111827", "Signal": "#4355FF", "Build": "#C8FF3D", "Cloud": "#F3F5F8",
    "Accent": "#42D7FF", "Base": "#FFFFFF", "Graphite": "#6B7280",
    "Graphite Deep": "#5F6875", "Hairline": "#E2E6EC", "Signal 700": "#2E3FE0",
    "Signal 300": "#8B98FF", "Signal 050": "#EDEFFF", "Cyan 700": "#0E7490",
    "Void": "#0A0E17", "Slate": "#1F2937", "Verified": "#166534", "Fault": "#C2313C",
    "Verified 300": "#7EE0A0", "Fault 300": "#FF8A94",
}
BACKGROUNDS = ["Base", "Cloud", "Ink", "Void", "Slate", "Build", "Signal"]


def _linear(channel: float) -> float:
    c = channel / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_colour: str) -> float:
    h = hex_colour.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _linear(r) + 0.7152 * _linear(g) + 0.0722 * _linear(b)


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def _self_check() -> None:
    """Validate the implementation against known WCAG reference pairs.

    Never skip this. The whole point of publishing ratios is that they are computed, and a
    silently wrong formula publishes confident nonsense.
    """
    for a, b, expected in (("#767676", "#FFFFFF", 4.54),
                           ("#000000", "#FFFFFF", 21.00),
                           ("#0000FF", "#FFFFFF", 8.59)):
        got = round(contrast(a, b), 2)
        if got != expected:
            raise SystemExit(f"contrast self-check failed: {a} on {b} = {got}, expected {expected}")


def _verdict(ratio: float) -> str:
    if ratio >= 7:
        return "AAA"
    if ratio >= 4.5:
        return "AA"
    return "AA-large" if ratio >= 3 else "fail"


def write_contrast_report() -> Path:
    _self_check()
    lines = [
        "# Contrast report", "",
        "Skilling brand kit v2.0. Generated by `brand/build.py` — do not hand-edit.", "",
        "Computed with the WCAG 2.x relative-luminance formula. The implementation is "
        "validated on every run against three known reference pairs: `#767676` on white = "
        "4.54:1, black on white = 21.00:1, and `#0000FF` on white = 8.59:1.", "",
        "`fail` is below 3:1. `AA-large` is 3:1–4.5:1, permitted only for text at 24px+, "
        "or 18.66px+ bold, or for non-text elements.", "",
        "## Foreground on background", "",
        "| Foreground | " + " | ".join(BACKGROUNDS) + " |",
        "|---|" + "---|" * len(BACKGROUNDS),
    ]
    for name, hexv in PALETTE.items():
        cells = []
        for bg in BACKGROUNDS:
            r = contrast(hexv, PALETTE[bg])
            cells.append(f"{r:.2f} {_verdict(r)}")
        lines.append(f"| {name} `{hexv}` | " + " | ".join(cells) + " |")

    lines += ["", "## Load-bearing pairings", "", "| Pairing | Ratio | Verdict |", "|---|---|---|"]
    for fg, bg, note in [
        ("Ink", "Base", "Default body text"),
        ("Ink", "Cloud", "Text on technical panels"),
        ("Ink", "Build", "The mark on a lime tile"),
        ("Graphite", "Cloud", "**Fails AA for small text.** Use Graphite Deep."),
        ("Graphite Deep", "Cloud", "Secondary type on Cloud"),
        ("Graphite Deep", "Base", "Passes on both — the safe default for secondary type"),
        ("Signal", "Base", "Links, compatibility chips"),
        ("Signal", "Ink", "**Fails.** Why the parent swaps its mark's unit to lime on dark."),
        ("Signal 300", "Void", "Links in dark mode"),
        ("Build", "Base", "**Fails.** Lime is a surface, never type."),
        ("Verified", "Base", "Validator pass, light"),
        ("Verified", "Void", "**Fails.** Use Verified 300."),
        ("Verified 300", "Void", "Validator pass, dark"),
        ("Fault", "Base", "Validator failure, light"),
        ("Fault", "Void", "**Fails.** Use Fault 300."),
        ("Fault 300", "Void", "Validator failure, dark"),
    ]:
        lines.append(f"| {fg} on {bg} | {contrast(PALETTE[fg], PALETTE[bg]):.2f}:1 | {note} |")

    lines += [
        "", "## Corrections to Future of Dev v1.0", "",
        "Recomputing the parent kit's published figures found four that drift. None causes a "
        "failure, but principle P3 says ratios are computed, not assumed.", "",
        "| Pairing | Published | Measured |", "|---|---|---|",
        f"| Ink on white | 16.4 | **{contrast('#111827', '#FFFFFF'):.2f}** |",
        f"| Ink on Cloud | 15.4 | **{contrast('#111827', '#F3F5F8'):.2f}** |",
        f"| Signal 700 on white | 7.0 | **{contrast('#2E3FE0', '#FFFFFF'):.2f}** |",
        f"| Cloud on Void | 18.8 | **{contrast('#F3F5F8', '#0A0E17'):.2f}** |",
        "", "## The mark is not a contrast problem", "",
        "The Cut's legibility constraint is figure–ground, not contrast. White on Ink measures "
        f"{contrast('#FFFFFF', '#111827'):.2f}:1 — an excellent ratio — and the mark is still "
        "unreadable, because at 80.1% coverage the channels are the counters, and inverting "
        "them turns the counters into strokes. No ratio can tell you that; it was found by "
        "rendering the mark and looking at it.",
    ]
    path = ASSETS / "tokens" / "contrast-report.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


# ---------------------------------------------------------------------------------------
# Geometry rasters — Pillow
# ---------------------------------------------------------------------------------------

def _tile(px: int, field, mark=INK, supersample: int = 8):
    from PIL import Image, ImageDraw
    big = Image.new("RGB", (px * supersample, px * supersample), field)
    draw = ImageDraw.Draw(big)
    k = px * supersample / 36.0          # 36x36 field, mark inset 4 on x
    draw.polygon([((x + 4) * k, y * k) for x, y in MARK_POLY], fill=mark)
    return big.resize((px, px), Image.LANCZOS)


def _bare(px: int, mark=INK, supersample: int = 8):
    from PIL import Image, ImageDraw
    big = Image.new("RGBA", (px * supersample, px * supersample), (0, 0, 0, 0))
    draw = ImageDraw.Draw(big)
    k = px * supersample / 32.0
    draw.polygon([(x * k, y * k) for x, y in MARK_POLY], fill=mark + (255,))
    return big.resize((px, px), Image.LANCZOS)


def build_rasters() -> int:
    from PIL import Image  # noqa: F401  (fail early with a clear error if absent)
    count = 0
    for name, field in FIELDS.items():
        d = ASSETS / "tiles" / "png"
        d.mkdir(parents=True, exist_ok=True)
        for size in (512, 256, 128, 64):
            _tile(size, field).save(d / f"skilling-tile-{name}-{size}.png")
            count += 1

    d = ASSETS / "mark" / "png"
    d.mkdir(parents=True, exist_ok=True)
    for size in (512, 256, 128, 64, 32):
        _bare(size).save(d / f"skilling-mark-ink-{size}.png")
        count += 1

    d = ASSETS / "favicon"
    for size in (16, 32, 48, 64):
        _tile(size, CLOUD).save(d / f"favicon-{size}.png")
        count += 1
    ico = [_tile(s, CLOUD) for s in (16, 32, 48, 64)]
    ico[0].save(d / "favicon.ico", format="ICO",
                sizes=[(16, 16), (32, 32), (48, 48), (64, 64)], append_images=ico[1:])
    count += 1
    _tile(180, BUILD).save(d / "apple-touch-icon-180.png")
    _tile(192, BUILD).save(d / "android-chrome-192.png")
    _tile(512, BUILD).save(d / "android-chrome-512.png")
    count += 3

    d = ASSETS / "github"
    d.mkdir(parents=True, exist_ok=True)
    _tile(460, BUILD).save(d / "avatar-460.png")
    _tile(460, CLOUD).save(d / "avatar-460-cloud.png")
    count += 2
    return count


