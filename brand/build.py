SKIP = {".DS_Store", "_shell.html"}


def _badge_slug(label: str, msg: str) -> str:
    return f"{label}-{msg}".lower().replace(" ", "-").replace(".", "").replace("/", "-")


def _is_stale_badge(path: Path) -> bool:
    """True for badge SVGs left over from an earlier BADGES set.

    Some mounts disallow unlink, so superseded badges can linger on disk. A badge that
    states a fact the repo no longer holds is worse than no badge, so they are excluded
    from the zip rather than trusted to have been cleaned up.
    """
    if path.suffix != ".svg" or path.parent.name != "badges":
        return False
    current = {_badge_slug(label, msg) for label, msg, _, _ in BADGES}
    return path.stem not in current


# Launch files that live in the repo root rather than under brand/, but which someone
# taking this pack to a fresh GitHub repo needs in the same download.
REPO_FILES = (
    ".github/ISSUE_TEMPLATE/config.yml",
    ".github/ISSUE_TEMPLATE/spec-ambiguity.yml",
    ".github/ISSUE_TEMPLATE/validator-bug.yml",
    ".github/ISSUE_TEMPLATE/conformance-claim.yml",
    ".github/PULL_REQUEST_TEMPLATE.md",
    "CODE_OF_CONDUCT.md",
    "SECURITY.md",
)


def build_zip() -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    target = OUT / f"{PACK}.zip"
    n = 0
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        # Everything under brand/, including build.py itself — the pack should be able to
        # rebuild itself from its own contents.
        for path in sorted(ROOT.rglob("*")):
            if not path.is_file():
                continue
            if OUT in path.parents or path.name in SKIP or path.suffix == ".pyc":
                continue
            if _is_stale_badge(path):
                continue
            z.write(path, f"{PACK}/{path.relative_to(ROOT)}")
            n += 1
        # Repo furniture, namespaced so it is obvious where it belongs.
        repo_root = ROOT.parent
        for rel in REPO_FILES:
            src = repo_root / rel
            if src.is_file():
                z.write(src, f"{PACK}/repo-files/{rel}")
                n += 1
    with zipfile.ZipFile(target) as z:
        if z.testzip() is not None:
            raise SystemExit("zip integrity check failed")
    print(f"  {target.relative_to(ROOT.parent)} — {n} files, {target.stat().st_size / 1024:.0f} KB")
    return target


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--with-browser", action="store_true",
                    help="also render banners, social preview, masthead and badges")
    ap.add_argument("--zip", action="store_true", help="assemble the distributable zip")
    ap.add_argument("--only-report", action="store_true",
                    help="regenerate the contrast report and nothing else (stdlib only)")
    args = ap.parse_args()

    print("Skilling brand pack")
    report = write_contrast_report()
    print(f"  contrast report  → {report.relative_to(ROOT)} (self-check passed)")
    if args.only_report:
        return

    print(f"  geometry rasters → {build_rasters()} files")
    if args.with_browser:
        print(f"  browser assets   → {build_browser_assets()} files")
    else:
        print("  browser assets   → skipped (pass --with-browser)")
    if args.zip:
        build_zip()


if __name__ == "__main__":
    main()
