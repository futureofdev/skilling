FONT_LINK = ('<link href="https://fonts.googleapis.com/css2?'
             'family=Archivo:wdth,wght@62..125,100..900&'
             'family=Inter:wght@400;500;600;700&'
             'family=JetBrains+Mono:wght@400;500;700&display=swap" rel="stylesheet">')

# Every badge here states something checkable, and the unflattering ones stay.
# "independent implementations: 0" is the honest number while every row in
# docs/implementations.md shares one author — and this project's whole argument is
# that a registry of one is honest rather than impressive. Bump these by hand when
# the underlying fact changes; a badge that drifts from the repo is worse than no badge.
BADGES = [
    # label, message, message background, message text colour
    ("spec", "1.4.0-draft", "#4355FF", "#FFFFFF"),
    ("licence", "Apache-2.0", "#6B7280", "#FFFFFF"),
    ("spec text", "CC BY 4.0", "#6B7280", "#FFFFFF"),
    ("independent implementations", "0", "#6B7280", "#FFFFFF"),
    ("conformance", "self-certified", "#6B7280", "#FFFFFF"),
    ("reference runtime", "no model required", "#4355FF", "#FFFFFF"),
    ("pypi", "skilling", "#4355FF", "#FFFFFF"),
    ("built with", "Skilling", "#C8FF3D", "#111827"),
]
# shields.io convention: an SVG behind <img> cannot load a webfont, so badges use Verdana.
BADGE_FONT = "Verdana,'DejaVu Sans',Geneva,sans-serif"


def _tile_markup(size: int, field: str, fill: str = "#111827") -> str:
    k = size / 36
    return (f'<g transform="scale({k})"><rect width="36" height="36" fill="{field}"/>'
            f'<g transform="translate(4,0)"><path d="{MARK_PATH}" fill="{fill}"/></g></g>')


def build_browser_assets() -> int:
    from playwright.sync_api import sync_playwright

    import tempfile

    count = 0
    # Scratch file lives outside the tree: some mounts disallow unlink, and a stray
    # _shell.html inside dist/ would otherwise end up in the zip.
    tmpdir = Path(tempfile.mkdtemp(prefix="skilling-brand-"))
    shell = tmpdir / "_shell.html"

    with sync_playwright() as pw:
        browser = pw.chromium.launch(args=["--no-sandbox", "--disable-dev-shm-usage"])

        def render(path: Path, width: int, height: int, body: str, scale: int = 1) -> None:
            shell.write_text(
                f"<!DOCTYPE html><html><head><meta charset=utf-8>{FONT_LINK}"
                "<style>*{box-sizing:border-box}html,body{margin:0;padding:0;"
                "background:transparent}"
                ".wm{font-family:Archivo;font-weight:800;"
                "font-variation-settings:'wdth' 112,'wght' 800;letter-spacing:-.03em;"
                "line-height:1}.bd{font-family:Inter}"
                ".mo{font-family:'JetBrains Mono';font-weight:500}</style>"
                f"</head><body>{body}</body></html>", encoding="utf-8")
            page = browser.new_page(viewport={"width": width, "height": height},
                                    device_scale_factor=scale)
            page.goto(shell.as_uri())
            page.wait_for_timeout(2200)
            path.parent.mkdir(parents=True, exist_ok=True)
            page.screenshot(path=str(path), omit_background=True)
            page.close()

        # --- badges: measure the text, then emit exact-width SVGs -----------------------
        measure = browser.new_page()
        measure.set_content(f"<!DOCTYPE html><html><head>{FONT_LINK}</head>"
                            '<body><svg id="s" width="3000" height="200"></svg></body></html>')
        measure.wait_for_timeout(1500)
        strings = sorted({s for pair in BADGES for s in pair[:2]})
        widths = measure.evaluate(
            """(payload) => {
                const NS='http://www.w3.org/2000/svg';
                const svg=document.getElementById('s'); const out={};
                for(const s of payload.strings){
                  const t=document.createElementNS(NS,'text');
                  t.setAttribute('style',`font-family:${payload.font};font-size:110px`);
                  t.setAttribute('x',0); t.setAttribute('y',0);
                  t.textContent=s; svg.appendChild(t);
                  out[s]=t.getComputedTextLength()/10.0;   // width at 11px
                  t.remove();
                }
                return out;
            }""", {"strings": strings, "font": BADGE_FONT})
        measure.close()

        badge_dir = ASSETS / "github" / "badges"
        badge_dir.mkdir(parents=True, exist_ok=True)
        for label, msg, colour, text_colour in BADGES:
            lw = round(widths[label] + 10, 1)
            mw = round(widths[msg] + 10, 1)
            total, height = round(lw + mw, 1), 20
            slug = f"{label}-{msg}".lower().replace(" ", "-").replace(".", "").replace("/", "-")
            (badge_dir / f"{slug}.svg").write_text(
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                f'<svg xmlns="http://www.w3.org/2000/svg" width="{total}" height="{height}" '
                f'viewBox="0 0 {total} {height}" role="img" aria-label="{label}: {msg}">\n'
                f'  <title>{label}: {msg}</title>\n'
                f'  <rect width="{lw}" height="{height}" fill="#111827"/>\n'
                f'  <rect x="{lw}" width="{mw}" height="{height}" fill="{colour}"/>\n'
                f'  <g font-family="{BADGE_FONT}" font-size="11" text-anchor="middle">\n'
                f'    <text x="{lw / 2}" y="14" fill="#FFFFFF">{label}</text>\n'
                f'    <text x="{lw + mw / 2}" y="14" fill="{text_colour}">{msg}</text>\n'
                '  </g>\n</svg>\n', encoding="utf-8")
            count += 1

        # --- README banners -------------------------------------------------------------
        def banner(dark: bool) -> str:
            bg = "#0A0E17" if dark else "#FFFFFF"
            fg = "#F3F5F8" if dark else "#111827"
            muted = "#97A1B2" if dark else "#5F6875"
            # Field rule: on a light page the page is already the field, so the mark goes
            # bare. Only the dark banner needs to carry its own.
            mark = (f'<svg width="104" height="104" viewBox="0 0 36 36">{_tile_markup(36, "#C8FF3D")}</svg>'
                    if dark else
                    f'<svg width="91" height="91" viewBox="0 0 32 32">'
                    f'<path d="{MARK_PATH}" fill="#111827"/></svg>')
            return (f'<div style="width:1280px;height:320px;background:{bg};display:flex;'
                    'align-items:center;padding:0 84px;">'
                    '<div style="display:flex;align-items:center;gap:34px;">'
                    f'{mark}'
                    '<div>'
                    # Learner-first: the benefit leads, the format is how it is delivered.
                    # Authors get the second line, never the first.
                    f'<div class="wm" style="font-size:76px;color:{fg};margin-bottom:14px;">Skilling</div>'
                    f'<div class="bd" style="font-size:21px;color:{muted};">Learn one-to-one, '
                    'with Claude Code or Codex.</div>'
                    f'<div class="mo" style="font-size:15px;color:{muted};margin-top:12px;">'
                    'Start a course · skilling 0.5.0</div>'
                    '</div></div></div>')

        gh = ASSETS / "github"
        render(gh / "readme-banner-light.png", 1280, 320, banner(False)); count += 1
        render(gh / "readme-banner-dark.png", 1280, 320, banner(True)); count += 1

        # --- social preview: GitHub requires exactly 1280x640 ----------------------------
        social = (
            '<div style="width:1280px;height:640px;background:#FFFFFF;display:flex;'
            'flex-direction:column;justify-content:space-between;padding:76px 84px;">'
            '<div style="display:flex;align-items:center;gap:26px;">'
            f'<svg width="84" height="84" viewBox="0 0 36 36">{_tile_markup(36, "#F3F5F8")}</svg>'
            '<span class="mo" style="font-size:17px;color:#5F6875;letter-spacing:.14em;'
            'text-transform:uppercase;">Open format · 1.4.0-draft</span></div>'
            '<div><div class="wm" style="font-size:150px;color:#111827;margin-bottom:26px;">'
            'Skilling</div>'
            '<div class="bd" style="font-size:34px;color:#5F6875;line-height:1.35;max-width:32ch;">'
            'Learn one-to-one with Claude Code or Codex. The course and record you earn '
            'stay yours.</div></div>'
            # The mono signature is the command, not a file extension. `.skilling` in this
            # project is a hidden state directory, not a package format — see the brand
            # kit's note on retiring the format lockup.
            # Learner-first: `start` creates the portable workspace a learner opens.
            '<div style="display:flex;align-items:center;justify-content:space-between;">'
            '<span class="mo" style="font-size:19px;color:#111827;">skilling start · 0.5.0</span>'
            '<span class="mo" style="font-size:15px;color:#5F6875;letter-spacing:.12em;'
            'text-transform:uppercase;">Created by Future of Dev</span></div></div>')
        render(gh / "social-preview-1280x640.png", 1280, 640, social); count += 1

        # --- email masthead: flat PNG on lime, so client inversion cannot touch it -------
        masthead = ('<div style="width:280px;height:44px;background:#FFFFFF;display:flex;'
                    'align-items:center;gap:14px;padding:0 4px;">'
                    f'<svg width="36" height="36" viewBox="0 0 36 36">{_tile_markup(36, "#C8FF3D")}</svg>'
                    '<span class="wm" style="font-size:30px;color:#111827;">Skilling</span></div>')
        email = ASSETS / "email"
        render(email / "masthead-lime-1x.png", 280, 44, masthead, scale=1); count += 1
        render(email / "masthead-lime-2x.png", 280, 44, masthead, scale=2); count += 1

        browser.close()

    import shutil

    shutil.rmtree(tmpdir, ignore_errors=True)  # best-effort: never fail the build on cleanup
    return count


